"""Build the Overleaf-ready package submission/ from paper/ and paper_assets/ (no raw data).

- Copies paper/main.tex with asset paths rewritten from ../paper_assets/ to paper_assets/ (compiles from the
  package root).
- Copies paper_assets/tables, paper_assets/figures and paper_assets/numbers.tex.
- Computes SHA-256 of the raw inputs (for the top-level README), writes results/tables/input_hashes.json.
- Writes submission/README.md (compile order) and results/tables/submission_check.json.
The bibliography is inline (thebibliography) in main.tex; its entries are listed in REFERENCES_TO_VERIFY.md.
"""
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from habitid.utils.config import PAPER, PAPER_ASSETS, RAW, RESEARCH, RESULTS  # noqa: E402
from habitid.utils.runtime import write_json  # noqa: E402

SUB = RESEARCH / "submission"


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


LICENSES = {
    "DSL-StrongPasswordData.csv": "CMU keystroke benchmark (Killourhy and Maxion). License NOT verified in this study; check the source page before redistribution.",
    "fixed-text.csv": "KeyRecs (Zenodo 10.5281/zenodo.7886742). CC BY 4.0 (checked on the Zenodo record page).",
    "free-text.csv": "KeyRecs (Zenodo 10.5281/zenodo.7886742). CC BY 4.0 (checked on the Zenodo record page). Not used in the paper.",
    "demographics.csv": "KeyRecs (Zenodo 10.5281/zenodo.7886742). CC BY 4.0 (checked on the Zenodo record page). Not used as a model input.",
    "archive.zip": "MotionSense (Kaggle mirror). Original license NOT verified in this study; check the dataset page before redistribution.",
    "information-15-00511.pdf": "IKDD paper (PDF only). No IKDD data were used. Licence of the PDF not checked.",
    "LaTeX paper.zip": "Author's draft (not a dataset).",
}


def top_readme(hashes: dict) -> str:
    rows = "\n".join(f"| `{n}` | `{h}` | {LICENSES.get(n, '')} |" for n, h in hashes.items())
    return f"""# habitID-Net research pipeline

Human versus automated session discrimination for passive behavioral scoring. This is NOT identity verification.
All synthetic automated sessions are generated by the code in this repository.

## One-command reproduction

Requirements: Python 3.13 on Windows or Linux, CPU only. Pinned in `requirements.txt`.

    pip install -r requirements.txt
    make all            # or, on Windows: powershell -ExecutionPolicy Bypass -File run_all.ps1

`make all` runs tests, the data audit, canonical builds, folds and attacker corpora, baselines, the CV reliability
experiment, the timing probe, training (main, ablation and LOFO groups), evaluation, transfer and OTP sensitivity,
ONNX export, paper assets and the submission package. Training is the long step (several hours on 18 CPU threads).
Runs that already exist are skipped, so the pipeline can be resumed.

Raw datasets are not in this repository. Place them in `../raw dataset/` (see the table below).

## Pinned requirements

See `requirements.txt` (numpy 2.4.4, pandas 3.0.2, scipy 1.17.1, scikit-learn 1.8.0, PyYAML 6.0.3, matplotlib 3.10.8,
torch 2.11.0 (CPU), pytest 8.2.0, onnx 1.23.2, onnxscript 0.7.2, onnxruntime 1.31.0).

## Data sources, licenses, and SHA-256 of inputs

Licenses marked NOT verified were not checked in this study. Check the source page before any redistribution.

| file | SHA-256 | license / status |
|---|---|---|
{rows}

Sources: CMU keystroke benchmark (Killourhy and Maxion, 2009); KeyRecs (Dias et al., Data in Brief 2023, Zenodo
10.5281/zenodo.7886742); MotionSense (Kaggle mirror of the Malekzadeh et al. dataset).
OTP latency: no public data. The OTP model is ASSUMED (`configs/otp_assumptions.yaml`).

## Layout

- `configs/` all tunable values (default.yaml, otp_assumptions.yaml, v0_weights.yaml)
- `src/habitid/` library code
- `scripts/` numbered pipeline (00 audit to 13 submission)
- `tests/` leakage, Verhoeff, v0 reproduction, conformal coverage, shapes
- `results/` raw per-run outputs and tables (never hand-edited)
- `paper/` paper source; `paper_assets/` generated tables, figures and macros
- `submission/` Overleaf package (no raw data)
- `PROGRESS.md`, `DEVIATIONS.md`, `CLAIMS_CHECK.md`, `FACULTY_SUMMARY.md`, `REFERENCES_TO_VERIFY.md`
"""


def main():
    if SUB.exists():
        shutil.rmtree(SUB)
    (SUB / "paper_assets").mkdir(parents=True)
    tex = (PAPER / "main.tex").read_text(encoding="utf-8")
    tex = tex.replace("../paper_assets/", "paper_assets/")
    (SUB / "main.tex").write_text(tex, encoding="utf-8")
    shutil.copytree(PAPER_ASSETS / "tables", SUB / "paper_assets" / "tables")
    shutil.copytree(PAPER_ASSETS / "figures", SUB / "paper_assets" / "figures")
    shutil.copy2(PAPER_ASSETS / "numbers.tex", SUB / "paper_assets" / "numbers.tex")

    raw_inputs = ["DSL-StrongPasswordData.csv", "fixed-text.csv", "free-text.csv", "demographics.csv",
                  "archive.zip", "information-15-00511.pdf", "LaTeX paper.zip"]
    hashes = {n: sha256(RAW / n) for n in raw_inputs if (RAW / n).exists()}
    write_json(RESULTS / "tables" / "input_hashes.json", hashes)

    readme = """# habitID-Net paper: compile in Overleaf or with pdflatex

Compile from this folder (the package root). Paths are relative to it.

Compile order (run twice so references resolve):

    pdflatex main.tex
    pdflatex main.tex

Overleaf: upload this whole folder, set main.tex as the main document, and compile with pdfLaTeX.
The IEEEtran class is needed (it is included with Overleaf). The bibliography is inline (thebibliography);
entries that still need manual verification are listed in REFERENCES_TO_VERIFY.md in the research folder.

Contents:
- main.tex                 the paper
- paper_assets/tables/     generated LaTeX tables (from results/ only)
- paper_assets/figures/    generated figures (PDF and PNG)
- paper_assets/numbers.tex generated \\newcommand macros for numbers quoted in the text

The TeX source has one remaining \\TBD: the acknowledgment (course, instructor, compute resources).
"""
    (SUB / "README.md").write_text(readme, encoding="utf-8")

    bib = re.findall(r"\\bibitem\{([^}]+)\}\s*(.*?)(?=\\bibitem|\\end\{thebibliography\})", tex, flags=re.S)
    lines = ["# References to verify manually", "",
             "Generated by `scripts/13_build_submission.py` from the inline bibliography of `paper/main.tex`.",
             "No entry was checked against its source in this study. Every entry needs manual verification",
             "(authors, year, venue, volume, pages, DOI) before submission.", ""]
    for key, text in bib:
        text = " ".join(text.split())
        lines.append(f"- [ ] **{key}**: {text}  **NEEDS MANUAL VERIFICATION**")
    lines += ["", "Known points to check first:",
              "- The MotionSense reference (malekzadeh2019) title and venue were written from memory and must be checked against the dataset's own publication.",
              "- Killourhy and Maxion (2009): the number of detectors compared was removed from the text; check the paper's own claim before adding one back.",
              "- arXiv identifier in angelopoulos2021 (2107.07511): check the arXiv record."]
    (RESEARCH / "REFERENCES_TO_VERIFY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (RESEARCH / "README.md").write_text(top_readme(hashes), encoding="utf-8")

    checks = {
        "tex_inputs_resolve": all((SUB / m).exists() for m in re.findall(r"\\input\{([^}]+)\}", tex)),
        "includegraphics_resolve": all((SUB / m).exists() for m in re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex)),
        "no_relative_parent_paths": "../" not in tex,
        "files": sorted(str(p.relative_to(SUB)).replace("\\", "/") for p in SUB.rglob("*") if p.is_file()),
        "raw_data_included": False,
    }
    write_json(RESULTS / "tables" / "submission_check.json", checks)
    print(json.dumps({k: v for k, v in checks.items() if k != "files"}, indent=1))
    print("files:", len(checks["files"]))


if __name__ == "__main__":
    main()
